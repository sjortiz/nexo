"""`nexo.lock`: the setup file fully resolved, so upgrades never move pins silently.

The lock records which components are on, every service's image and the model each role
uses. Pins stay put while the setup file changes; `--upgrade` moves them to the defaults
in the fragments. It never holds secrets.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

import yaml

from nexo.local_profiles import plan
from nexo.setup.components import COMPONENTS, DEFAULT_ON, default_images
from nexo.setup.schema import API_VERSION, ROLES, Casting, Models, Ports, SetupError

HEADER = (
    "# Generated by `nexo setup lock` from {source}. Do not edit; change {source}.\n"
)


def casting_hash(path: Path) -> str:
    """sha256 of the setup file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def enabled_components(casting: Casting) -> dict[str, bool]:
    """Every component and whether this setup turns it on."""
    spec = casting.spec
    overrides = {
        name: c.enabled for name, c in spec.addons.items() if c.enabled is not None
    }
    enabled = {name: name in DEFAULT_ON for name in COMPONENTS}
    enabled |= overrides
    enabled["vllm"] = spec.models.provider == "vllm"
    return enabled


def vllm_urls(ports: Ports) -> tuple[str, str]:
    """The vLLM chat and embedding servers as the host sees them."""
    return (
        f"http://localhost:{ports.vllm}/v1",
        f"http://localhost:{ports.vllm_embedding}/v1",
    )


def resolve_models(models: Models, ports: Ports) -> dict[str, dict[str, str | None]]:
    """Role -> model and server, as Nexo will resolve them (explicit roles win)."""
    resolved: dict[str, dict[str, str | None]] = {}
    if models.provider == "ollama":
        local = f"http://localhost:{models.local.port}/v1"
        if models.remote is None:
            placement = {
                r: (m, local) for r, m in plan(models.local.profile).roles.items()
            }
        else:
            remote = f"http://localhost:{models.remote.port}/v1"
            heavy = plan(models.remote.profile, "heavy").roles
            light = plan(models.local.profile, "light").roles
            placement = {r: (m, remote) for r, m in heavy.items()}
            placement |= {r: (m, local) for r, m in light.items()}
        resolved = {r: {"model": m, "server": url} for r, (m, url) in placement.items()}
    elif models.provider == "vllm":
        chat, embedding = vllm_urls(ports)
        resolved = {r: {"model": models.vllm.model, "server": chat} for r in ROLES}
        resolved["embedding"] = {"model": models.vllm.embedding, "server": embedding}
    for role, override in models.roles.items():
        entry = resolved.setdefault(role, {"model": None, "server": None})
        entry["model"] = override.model or entry["model"]
        entry["server"] = override.base_url or entry["server"]
    return {role: resolved[role] for role in ROLES if role in resolved}


def _images(
    casting: Casting, root: Path, previous: dict[str, Any], upgrade: bool
) -> dict[str, dict[str, str]]:
    """Component -> service -> image: setup file > previous pin > fragment default."""
    spec = casting.spec
    overrides = spec.components | spec.addons
    pins: dict[str, dict[str, str]] = {}
    for name, component in COMPONENTS.items():
        images = default_images(root, name)
        if not upgrade:
            old = previous.get(name, {})
            images |= {svc: img for svc, img in old.items() if svc in images}
        override = overrides.get(name)
        if override is not None:
            if override.image:
                images[component.main] = override.image
            unknown = set(override.images) - set(images)
            if unknown:
                raise SetupError(f"{name}: no services named {sorted(unknown)}")
            images |= override.images
        if images:
            pins[name] = dict(sorted(images.items()))
    return pins


def resolve(
    casting: Casting, root: Path, previous: dict[str, Any] | None, upgrade: bool
) -> dict[str, Any]:
    """The lock document for a setup file."""
    old_images = (previous or {}).get("images", {})
    return {
        "apiVersion": API_VERSION,
        "kind": "SetupLock",
        "name": casting.metadata.name,
        "enabled": enabled_components(casting),
        "images": _images(casting, root, old_images, upgrade),
        "models": resolve_models(casting.spec.models, casting.spec.ports),
    }


def lock(
    casting: Casting, casting_path: Path, root: Path, *, upgrade: bool = False
) -> dict[str, Any]:
    """Read the lock next to the setup file, re-resolving it when the file changed."""
    lock_path = casting_path.with_suffix(".lock")
    digest = casting_hash(casting_path)
    previous = None
    if lock_path.exists():
        previous = yaml.safe_load(lock_path.read_text(encoding="utf-8")) or {}
        if previous.get("source", {}).get("sha256") == digest and not upgrade:
            return previous
    document = {"source": {"file": casting_path.name, "sha256": digest}}
    document |= resolve(casting, root, previous, upgrade)
    lock_path.write_text(
        HEADER.format(source=casting_path.name)
        + yaml.safe_dump(document, sort_keys=False),
        encoding="utf-8",
    )
    return document
