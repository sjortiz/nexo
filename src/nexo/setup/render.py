"""Render a setup file and its lock into plain files under `.nexo/render/`.

    compose.yaml         the services this setup turns on, images from the lock
    otel-collector.yaml  the base collector config plus each enabled add-on's pipeline
    nexo.env             what Nexo reads after .env: model servers, profiles, endpoints

target.mode native keeps Nexo, Neo4j and the models on this machine: compose.yaml then holds only
the telemetry and add-on containers (none at all with telemetry off and no add-ons, and no
compose file). Each render removes files the previous mode left, so nexo.env matches nexo.yaml.
The folder holds machine-specific values (paths, the container socket) and no secrets.
`make compose-file` also renders the mac-single preset portably (repo-relative paths, socket and
host name left to compose) into the committed docker-compose.yml and deploy/rendered/.
"""

from __future__ import annotations

import re
from collections.abc import Collection
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import jsonpatch
import yaml

from nexo.setup.components import COMPONENTS, load_fragment, merge_compose, merge_patch
from nexo.setup.lock import resolve, vllm_urls
from nexo.setup.engine import PodmanMachine
from nexo.setup.schema import NEEDS_COLLECTOR, Casting, Ports, SetupError

COLLECTOR_BASE = "deploy/otel-collector.yaml"
QUERY_TEXT = "nexo.query.text"
RENDER_DIR = ".nexo/render"
PORTABLE_PRESET = "examples/setups/mac-single/nexo.yaml"
PORTABLE_DIR = "deploy/rendered"
HEADER = "# Rendered by `nexo setup render`; edit nexo.yaml instead.\n"
# nexo.env records the setup file it came from, so Nexo can tell when it is stale.
SOURCE_LINE = "# source: {file} sha256 {digest}\n"
PORTABLE_HEADER = """\
# Generated by `make compose-file` from examples/setups/mac-single/nexo.yaml: one Mac, Neo4j,
# the collector and SigNoz with host metrics. Do not edit: change deploy/compose/ or the preset,
# then run make compose-file. Secrets come from the environment, never a file: run it as
#   nexo setup compose up -d    (passes them from ~/.config/nexo/config; or make up)
# Plain podman compose up -d needs them exported in its environment (local machines only).
# Other setups and add-ons: nexo.yaml and make up (docs/operations/local-setup.md).
"""
# Order of services in compose.yaml and of pipelines in the collector config.
ORDER = (
    "neo4j",
    "collector",
    "signoz",
    "hostMetrics",
    "langfuse",
    "jaeger",
    "agentInbox",
    "vllm",
    "app",
)
COLLECTOR_ADDONS = NEEDS_COLLECTOR
# Components that run on the host, not in a container, in target.mode native.
HOST_COMPONENTS = frozenset({"neo4j", "app"})
# Each port a fragment publishes, by service and container port: the spec.ports field
# that sets its host port.
PUBLISHED = {
    ("neo4j", 7474): "neo4j_http",
    ("neo4j", 7687): "neo4j_bolt",
    ("otel-collector", 4318): "otlp",
    ("otel-collector", 8889): "metrics",
    ("signoz", 8080): "signoz",
    ("langfuse-web", 3000): "langfuse",
    ("langfuse-storage", 8333): "langfuse_storage",
    ("jaeger", 16686): "jaeger",
    ("agent-inbox", 3000): "agent_inbox",
    ("vllm-inference-service", 8000): "vllm",
    ("vllm-embedding-service", 8000): "vllm_embedding",
}
# URLs a service hands the browser, so they name host ports.
BROWSER_URLS = {
    "NEXTAUTH_URL": "langfuse",
    "LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT": "langfuse_storage",
}


class _Dumper(yaml.SafeDumper):
    """Plain YAML for people: no anchors, list items indented under their key."""

    def ignore_aliases(self, data: Any) -> bool:
        return True

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)


def dump_yaml(document: Any) -> str:
    """A rendered document as YAML, keys in insertion order."""
    return yaml.dump(document, Dumper=_Dumper, sort_keys=False, width=100)


@dataclass(frozen=True)
class Host:
    """Facts about the machine the stack renders for."""

    os: str  # macos | linux
    engine: str  # podman | docker
    socket: str  # the engine's API socket as containers see it
    hostname: str
    # Podman machine facts (macOS, or when the setup names one); `connection` is set only
    # for a named machine, so its commands do not depend on which machine is the default.
    machine: PodmanMachine | None = None
    running: tuple[str, ...] = ()
    connection: str = ""

    @property
    def cli(self) -> list[str]:
        """The engine's command line, pinned to the setup's machine when it names one."""
        return [self.engine] + (
            ["--connection", self.connection] if self.connection else []
        )

    @property
    def gateway(self) -> str:
        """How a container reaches services on the host (macOS)."""
        return (
            "host.containers.internal"
            if self.engine == "podman"
            else "host.docker.internal"
        )


def containers(casting: Casting, on: Collection[str]) -> set[str]:
    """The components that run as containers: all, or in native mode all but Neo4j and Nexo."""
    if casting.spec.target.mode == "native":
        return set(on) - HOST_COMPONENTS
    return set(on)


def _substitute(value: Any, variables: dict[str, str]) -> Any:
    """Resolve ${NAME} and ${NAME:-default} for render-time names; others stay for compose."""
    if isinstance(value, dict):
        return {k: _substitute(v, variables) for k, v in value.items()}
    if isinstance(value, list):
        return [_substitute(v, variables) for v in value]
    if isinstance(value, str):
        pattern = r"\$\{(" + "|".join(variables) + r")(?::-[^}]*)?\}"
        return re.sub(pattern, lambda m: variables[m.group(1)], value)
    return value


@dataclass(frozen=True)
class Layout:
    """Where the rendered files go (repo-relative) and how paths inside them are written."""

    root: Path
    compose_file: str = f"{RENDER_DIR}/compose.yaml"
    out: str = RENDER_DIR  # the collector config and nexo.env
    portable: bool = False  # repo-relative paths; socket and host name left to compose

    def path(self, target: Path) -> str:
        """A path as the compose file refers to it."""
        target = target.resolve()
        if not self.portable:
            return str(target)
        relative = target.relative_to(self.root.resolve()).as_posix()
        return "." if relative == "." else f"./{relative}"


def _rebase(source: str, base: Path, layout: Layout) -> str:
    return layout.path(base / source) if source.startswith(".") else source


def _rebase_paths(service: dict[str, Any], base: Path, layout: Layout) -> None:
    """Rewrite a fragment's relative bind mounts and build context for the compose file."""
    volumes = []
    for volume in service.get("volumes", []):
        if isinstance(volume, str):
            source, _, rest = volume.partition(":")
            volumes.append(
                f"{_rebase(source, base, layout)}:{rest}" if rest else volume
            )
        else:
            volumes.append(volume | {"source": _rebase(volume["source"], base, layout)})
    if volumes:
        service["volumes"] = volumes
    if isinstance(service.get("build"), str):
        service["build"] = _rebase(service["build"], base, layout)


def _compose_fragment(
    layout: Layout, name: str, images: dict[str, str]
) -> dict[str, Any]:
    component = COMPONENTS[name]
    fragment = load_fragment(layout.root, component.compose)
    base = (layout.root / component.compose).parent
    services = fragment.get("services", {})
    for service_name, service in services.items():
        _rebase_paths(service, base, layout)
        if service_name in images:
            service["image"] = images[service_name]
    return {k: v for k, v in fragment.items() if not k.startswith("x-")}


def _app_secrets(casting: Casting, on: set[str]) -> dict[str, str]:
    """Generated secrets the local nexo container reads, interpolated by compose.

    Local only: on your own machine compose hands them over as environment variables. A
    cluster mounts them as files instead (ADR-0017), never as environment variables.
    """
    keys = ["NEO4J_PASSWORD"]
    if casting.spec.models.provider == "vllm":
        keys += ["VLLM_API_KEY", "EMBEDDING_API_KEY"]
    if "langfuse" in on:  # nexo eval's experiments
        keys += ["LANGFUSE_PUBLIC_KEY", "LANGFUSE_SECRET_KEY"]
    return {key: f"${{{key}}}" for key in keys}


def _app_environment(casting: Casting, host: Host, on: set[str]) -> dict[str, str]:
    """Endpoints as the nexo container sees them (macOS: through the engine's gateway)."""
    models = casting.spec.models
    env = {
        "OTEL_EXPORTER_OTLP_ENDPOINT": "http://otel-collector:4318",
        "NEO4J_URI": "neo4j://neo4j:7687",
    }
    if "langfuse" in on:
        env["LANGFUSE_HOST"] = "http://langfuse-web:3000"
    if models.local is not None:
        env["LOCAL_BASE_URL"] = f"http://{host.gateway}:{models.local.port}/v1"
    if models.remote is not None:
        env["REMOTE_BASE_URL"] = f"http://{host.gateway}:{models.remote.port}/v1"
    if models.provider == "vllm":
        env["VLLM_BASE_URL"] = "http://vllm-inference-service:8000/v1"
        env["EMBEDDING_BASE_URL"] = "http://vllm-embedding-service:8000/v1"
    return env


def _apply_environment(
    services: dict[str, Any], casting: Casting, on: set[str]
) -> None:
    """Each component's `env` override, and the credentials add-ons need on the collector."""
    overrides = casting.spec.components | casting.spec.addons
    collector = services.get("otel-collector")
    collector_env = collector.setdefault("environment", {}) if collector else {}
    for name in on:
        component = COMPONENTS[name]
        if name in overrides and overrides[name].env:
            main = services[component.main].setdefault("environment", {})
            main.update(overrides[name].env)
        collector_env.update(component.collector_env)
    if "langsmith" in on:
        langsmith = casting.spec.addons.get("langsmith")
        collector_env["LANGSMITH_PROJECT"] = (langsmith and langsmith.project) or "nexo"
    if collector is not None and not collector_env:
        del collector["environment"]


def publish_ports(services: dict[str, Any], ports: Ports) -> None:
    """Host ports from spec.ports, and the browser-facing URLs that name them."""
    for name, service in services.items():
        published = []
        for mapping in service.get("ports", []):
            address, container = mapping.rsplit(":", 1)
            field_name = PUBLISHED.get((name, int(container)))
            if field_name is None:
                raise SetupError(f"{name} publishes {container}: no spec.ports field")
            ip = address.rpartition(":")[
                0
            ]  # "127.0.0.1:7687" -> 127.0.0.1; "7687" -> ""
            host_port = f"{getattr(ports, field_name)}:{container}"
            published.append(f"{ip}:{host_port}" if ip else host_port)
        if published:
            service["ports"] = published
        environment = service.get("environment", {})
        for variable, field_name in BROWSER_URLS.items():
            if str(environment.get(variable, "")).startswith("http://localhost:"):
                environment[variable] = f"http://localhost:{getattr(ports, field_name)}"


def _configure_app(
    app: dict[str, Any], casting: Casting, on: set[str], layout: Layout, host: Host
) -> None:
    """The nexo container: env files, the secrets it reads and how it reaches the host."""
    out = layout.root / layout.out
    app["env_file"] = [
        {"path": layout.path(layout.root / ".env"), "required": False},
        {"path": layout.path(out / "nexo.env"), "required": True},
    ]
    # The secrets Nexo reads, from the environment `nexo setup` gives compose: no file.
    app["environment"] = _app_secrets(casting, on)
    # Rootless Podman on Linux cannot reach the host's 127.0.0.1 from a bridge network.
    if host.os == "linux":
        app["network_mode"] = "host"
    else:
        app["environment"] |= _app_environment(casting, host, on)


def build_compose(
    casting: Casting, lock: dict[str, Any], on: set[str], layout: Layout, host: Host
) -> dict[str, Any]:
    """The compose file for the container components; it mounts the files in layout.out."""
    out = layout.root / layout.out
    on = containers(casting, on)
    compose: dict[str, Any] = {"name": lock["name"]}
    for name in ORDER:
        if name in on and COMPONENTS[name].compose:
            fragment = _compose_fragment(layout, name, lock["images"].get(name, {}))
            compose = merge_compose(compose, fragment)
    if "volumes" in compose:
        compose["volumes"] = {n: spec or {} for n, spec in compose["volumes"].items()}
    services = compose["services"]
    _apply_environment(services, casting, on)
    publish_ports(services, casting.spec.ports)
    if "otel-collector" in services:
        services["otel-collector"].setdefault("volumes", []).insert(
            0,
            f"{layout.path(out / 'otel-collector.yaml')}:/etc/otelcol/config.yaml:ro",
        )
    if "app" in on:
        _configure_app(services["nexo"], casting, on, layout, host)
    if casting.spec.models.provider == "vllm":
        _configure_vllm(services, casting.spec.models.vllm)
    if layout.portable:
        return compose
    return _substitute(
        compose, {"CONTAINER_SOCKET": host.socket, "NEXO_HOST": host.hostname}
    )


def _set_flags(command: list[str], values: dict[str, str]) -> list[str]:
    return [
        f"{flag}={values[flag]}" if (flag := arg.split("=", 1)[0]) in values else arg
        for arg in command
    ]


def _configure_vllm(services: dict[str, Any], vllm: Any) -> None:
    """The models and GPU count from models.vllm."""
    inference = services["vllm-inference-service"]
    inference["command"] = _set_flags(
        inference["command"],
        {
            "--model": vllm.model,
            "--served-model-name": vllm.model,
            "--tensor-parallel-size": str(vllm.gpus),
        },
    )
    inference["deploy"]["resources"]["reservations"]["devices"][0]["count"] = vllm.gpus
    embedding = services["vllm-embedding-service"]
    embedding["command"] = _set_flags(embedding["command"], {"--model": vllm.embedding})


def build_collector(casting: Casting, on: set[str], root: Path) -> dict[str, Any]:
    """The collector config: base, each enabled add-on's fragment, then the setup's config."""
    config = load_fragment(root, COLLECTOR_BASE)
    for name in COLLECTOR_ADDONS:
        if name in on:
            config = merge_compose(
                config, load_fragment(root, COMPONENTS[name].collector)
            )
    if casting.spec.telemetry.query_text:
        config = _keep_query_text(config)
    override = casting.spec.components.get("collector")
    if override is not None and override.config:
        config = merge_patch(config, override.config)
    return config


def _keep_query_text(config: dict[str, Any]) -> dict[str, Any]:
    """telemetry.queryText: self-hosted backends keep nexo.query.text; LangSmith never does."""
    strip = config["processors"]["attributes/strip-content"]["actions"]
    strip[:] = [a for a in strip if a.get("key") != QUERY_TEXT]
    pipelines = config["service"]["pipelines"]
    if "traces/langsmith" in pipelines:
        config["processors"]["attributes/strip-query"] = {
            "actions": [{"key": QUERY_TEXT, "action": "delete"}]
        }
        pipelines["traces/langsmith"]["processors"].insert(0, "attributes/strip-query")
    return config


def validate_collector(config: dict[str, Any]) -> None:
    """Every pipeline and extension refers to a defined component (otelcol would refuse)."""
    service = config.get("service", {})
    problems = [
        f"service.extensions: {ext}"
        for ext in service.get("extensions", [])
        if ext not in config.get("extensions", {})
    ]
    for pipeline, spec in service.get("pipelines", {}).items():
        for kind in ("receivers", "processors", "exporters"):
            problems += [
                f"{pipeline}.{kind}: {item}"
                for item in spec.get(kind, [])
                if item not in config.get(kind, {})
            ]
        if not spec.get("receivers") or not spec.get("exporters"):
            problems.append(f"{pipeline}: needs receivers and exporters")
    if problems:
        raise SetupError(
            "collector config refers to undefined components: " + "; ".join(problems)
        )


def secrets_options(casting: Casting) -> dict[str, str]:
    """NEXO_STACK and NEXO_SECRETS_*: which store holds this stack's secrets (no values)."""
    secrets = casting.spec.secrets
    options = {
        "NEXO_STACK": casting.metadata.name,
        "NEXO_SECRETS_PROVIDER": secrets.provider,
    }
    if secrets.file is not None and secrets.file.path:
        options["NEXO_SECRETS_FILE"] = secrets.file.path
    if secrets.sops is not None:
        options["NEXO_SECRETS_SOPS_FILE"] = secrets.sops.file
    if secrets.vault is not None:
        vault = secrets.vault
        options |= {
            "NEXO_SECRETS_VAULT_ADDR": vault.address or "",
            "NEXO_SECRETS_VAULT_MOUNT": vault.mount,
            "NEXO_SECRETS_VAULT_PATH": vault.path or f"nexo/{casting.metadata.name}",
            "NEXO_SECRETS_VAULT_TOKEN_ENV": vault.token_env,
        }
    return options


def build_env(casting: Casting, on: Collection[str] = ()) -> dict[str, str]:
    """Settings Nexo reads after .env (so the setup file wins); endpoints as the host sees them."""
    spec = casting.spec
    telemetry = spec.telemetry.enabled
    env = {
        "NEXO_SETUP_MODE": spec.target.mode,
        "NEO4J_URI": spec.ports.bolt,
        # Telemetry off: blank also overrides an endpoint left in .env. The collector's
        # published port is on this machine's loopback, in native mode too.
        "OTEL_EXPORTER_OTLP_ENDPOINT": (
            f"http://localhost:{spec.ports.otlp}" if telemetry else ""
        ),
        "OTEL_LOGS_EXPORTER": spec.telemetry.logs if telemetry else "none",
        "TRACE_QUERY_TEXT": "true" if spec.telemetry.query_text else "false",
        # Always set, like REVIEW_POLICY: a stale value in .env must not widen what is logged.
        "TELEMETRY_CONTENT_MAX_SENSITIVITY": spec.telemetry.content,
        # Always set (blank when off): nexo eval runs a Langfuse experiment when set.
        "LANGFUSE_HOST": (
            f"http://localhost:{spec.ports.langfuse}" if "langfuse" in on else ""
        ),
    }
    env |= secrets_options(casting)
    models = spec.models
    # Always set (blank when unused): a LOCAL_PROFILE left in .env would otherwise send
    # every role to Ollama under vLLM, or REMOTE_PROFILE split a single machine.
    env |= {"LOCAL_PROFILE": "", "REMOTE_PROFILE": ""}
    if models.provider == "ollama":
        env["LOCAL_PROFILE"] = models.local.profile
        env["LOCAL_BASE_URL"] = f"http://localhost:{models.local.port}/v1"
        if models.remote is not None:
            env["REMOTE_PROFILE"] = models.remote.profile
            env["REMOTE_BASE_URL"] = f"http://localhost:{models.remote.port}/v1"
    elif models.provider == "vllm":
        chat, embedding = vllm_urls(spec.ports)
        env |= {
            "VLLM_BASE_URL": chat,
            "VLLM_MODEL": models.vllm.model,
            "EMBEDDING_BASE_URL": embedding,
            "EMBEDDING_MODEL": models.vllm.embedding,
        }
    ports, defaults = spec.ports, Ports()
    if (ports.agent_inbox, ports.review_inbox) != (
        defaults.agent_inbox,
        defaults.review_inbox,
    ):  # the adapter on the host reads them; its defaults match
        env |= {
            "AGENT_INBOX_PORT": str(ports.agent_inbox),
            "REVIEW_INBOX_PORT": str(ports.review_inbox),
        }
    # Always set, even to the default: a REVIEW_POLICY left in .env would otherwise override
    # spec.review, e.g. relax always and release answers without a person.
    env["REVIEW_POLICY"] = spec.review
    for role, override in models.roles.items():
        if override.model:
            env[f"{role.upper()}_MODEL"] = override.model
        if override.base_url:
            env[f"{role.upper()}_BASE_URL"] = override.base_url
    return env


def _apply_patches(casting: Casting, files: dict[str, Any]) -> None:
    for patch in casting.spec.patches:
        if patch.target not in files or patch.target == "nexo.env":
            raise SetupError(
                f"patch target {patch.target!r}: expected one of compose.yaml, otel-collector.yaml"
            )
        try:
            files[patch.target] = jsonpatch.apply_patch(
                files[patch.target], patch.operations
            )
        except (jsonpatch.JsonPatchException, jsonpatch.JsonPointerException) as exc:
            raise SetupError(f"patch on {patch.target}: {exc}") from exc


def rendered_files(
    casting: Casting,
    lock: dict[str, Any],
    layout: Layout,
    host: Host,
    extra_addons: frozenset[str] = frozenset(),
) -> dict[str, str]:
    """Repo-relative path -> content of every rendered file."""
    on = enabled_set(lock, extra_addons)
    header = PORTABLE_HEADER if layout.portable else HEADER
    if source := lock.get("source"):
        header += SOURCE_LINE.format(file=source["file"], digest=source["sha256"])
    env_lines = [f"{key}={value}" for key, value in build_env(casting, on).items()]
    env_file = {f"{layout.out}/nexo.env": header + "\n".join(env_lines) + "\n"}
    needs_collector = on & set(NEEDS_COLLECTOR)
    if "collector" not in on and needs_collector:
        raise SetupError(
            f"telemetry.enabled is false, but {', '.join(sorted(needs_collector))}"
            " send through the collector"
        )
    if not any(COMPONENTS[name].compose for name in containers(casting, on)):
        if casting.spec.patches:
            raise SetupError("patches apply to container services, and none are on")
        return env_file  # native, nothing in containers
    documents: dict[str, Any] = {
        "compose.yaml": build_compose(casting, lock, on, layout, host)
    }
    if "collector" in on:
        documents["otel-collector.yaml"] = build_collector(casting, on, layout.root)
    _apply_patches(casting, documents)
    hosted = {"neo4j", "nexo"} & set(documents["compose.yaml"]["services"])
    if casting.spec.target.mode == "native" and hosted:
        raise SetupError(f"a patch added {sorted(hosted)}, which run on this machine")
    if "otel-collector.yaml" in documents:
        validate_collector(documents["otel-collector.yaml"])

    def dump(document: Any) -> str:
        return header + dump_yaml(document)

    files = {layout.compose_file: dump(documents["compose.yaml"])}
    if "otel-collector.yaml" in documents:
        files[f"{layout.out}/otel-collector.yaml"] = dump(
            documents["otel-collector.yaml"]
        )
    return files | env_file


def write_files(root: Path, files: dict[str, str]) -> None:
    """Write rendered files under root."""
    for relative, text in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def render(
    casting: Casting,
    lock: dict[str, Any],
    root: Path,
    host: Host,
    extra_addons: frozenset[str] = frozenset(),
) -> Path:
    """Write root/.nexo/render from the fragments under root/deploy; return its path.

    Files the previous render wrote and this one does not (compose.yaml after a switch to
    target.mode native) are removed, so nothing from the other mode applies.
    """
    files = rendered_files(casting, lock, Layout(root), host, extra_addons)
    out = root / RENDER_DIR
    if out.is_dir():
        for stale in out.iterdir():
            if stale.is_file() and f"{RENDER_DIR}/{stale.name}" not in files:
                stale.unlink()
    write_files(root, files)
    return out


def portable_files(casting: Casting, root: Path) -> dict[str, str]:
    """The committed docker-compose.yml and deploy/rendered/: fragment defaults, no lock."""
    layout = Layout(
        root, compose_file="docker-compose.yml", out=PORTABLE_DIR, portable=True
    )
    host = Host(os="macos", engine="podman", socket="", hostname="")
    return rendered_files(casting, resolve(casting, root, None, True), layout, host)


def enabled_set(lock: dict[str, Any], extra_addons: frozenset[str]) -> set[str]:
    """Components on for this run: the lock's plus per-run add-ons."""
    return {name for name, enabled in lock["enabled"].items() if enabled} | extra_addons
